from material3_vlc.render.svg import load_icon_inner_svg


def _ico(name: str, size: int = 18) -> str:
    """Render an inline official Material Symbols Rounded SVG inheriting `currentColor`."""
    inner = load_icon_inner_svg(name)
    return (
        f'<svg class="m3-ico" width="{size}" height="{size}" viewBox="0 -960 960 960" '
        f'fill="currentColor" aria-hidden="true" focusable="false">{inner}</svg>'
    )


